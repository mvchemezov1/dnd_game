    // --------------------------------------------------------------------------------------------
    // Количество подготовленных заклинаний (для классов, которые готовят: cleric, druid, wizard)
    // --------------------------------------------------------------------------------------------
    public static int PreparedSpellsCount(int level, int spellcastingAbilityModifier) =>
        level + Math.Max(1, spellcastingAbilityModifier);

    // --------------------------------------------------------------------------------------------
    // Проверка компонент: Verbal, Somatic, Material
    // --------------------------------------------------------------------------------------------
    public static bool HasVerbalComponent() => true; // зависит от заклинания
    public static bool HasSomaticComponent(string _) => true;      // параметр переименован в _
    public static bool HasMaterialComponent(string _, out string? materialName, out int? costGold)
    {
        materialName = null;
        costGold = null;
        return false;
    }

    // --------------------------------------------------------------------------------------------
    // Можно ли накладывать заклинание без свободной руки (для соматического компонента)?
    // --------------------------------------------------------------------------------------------
    public static bool CanPerformSomatic(bool hasFreeHand) => hasFreeHand;

    // --------------------------------------------------------------------------------------------
    // Можно ли заменить материальный компонент фокусировкой?
    // --------------------------------------------------------------------------------------------
    public static bool CanUseArcaneFocus(bool hasFocus) => hasFocus;

    // --------------------------------------------------------------------------------------------
    // Правила бонусного действия и заклинаний
    // --------------------------------------------------------------------------------------------
    public static bool CanCastActionSpellAfterBonusAction(string spellCastAsAction)
    {
        // Если бонусным действием наложено заклинание, то основным действием можно наложить только заговор.
        return IsCantrip(spellCastAsAction);
    }
    public static bool RequiresConcentration(string spellId)
    {
        if (string.IsNullOrEmpty(spellId))
        {
            throw new ArgumentException($"\"{nameof(spellId)}\" не может быть неопределенным или пустым.", nameof(spellId));
        }

        return true; // или логика, не зависящая от других параметров
    }

    public static bool IsCantrip(string spellId)
    {
        if (string.IsNullOrEmpty(spellId))
        {
            throw new ArgumentException($"\"{nameof(spellId)}\" не может быть неопределенным или пустым.", nameof(spellId));
        }

        return true;
    }

    public static int ConcentrationCheckDC(int damageTaken) =>
        Math.Max(10, damageTaken / 2);

    // --------------------------------------------------------------------------------------------
    // Дистанция
    // --------------------------------------------------------------------------------------------
    public static int SpellRange() => 60; // футы

    public static bool IsTargetInRange(int distanceFeet, int spellRangeFeet) =>
        distanceFeet <= spellRangeFeet;

    // --------------------------------------------------------------------------------------------
    // Цели и области
    // --------------------------------------------------------------------------------------------
    public static int MaxTargets() => 1; // заглушка
    public static int AreaRadius() => 0;

    // --------------------------------------------------------------------------------------------
    // Ритуалы
    // --------------------------------------------------------------------------------------------
    public static bool IsRitual() => false;
    public static int RitualCastingTimeMinutes() => 10; // обычно +10 минут

    // --------------------------------------------------------------------------------------------
    // Контрзаклинание (Counterspell)
    // --------------------------------------------------------------------------------------------
    public static bool CanCounterSpell(int slotLevelAvailable, int targetSpellLevel, int abilityCheckBonus = 0)
    {
        if (slotLevelAvailable >= targetSpellLevel)
            return true;
        // Если ячейка ниже, требуется проверка способности (обычно Intelligence для wizard) против DC 10 + spell level
        int dc = 10 + targetSpellLevel;
        // Здесь мы не можем бросить бросок, но можно вернуть необходимость проверки
        // В статическом методе без броска - просто предполагаем, что проверка пройдена, если бонус достаточен? 
        // Лучше оставить логику в вызывающем коде.
        return abilityCheckBonus >= dc; // упрощённо
    }

    // --------------------------------------------------------------------------------------------
    // Диспелл (Dispel Magic)
    // --------------------------------------------------------------------------------------------
    public static int DispelCheckDC(int targetSpellLevel) =>
        10 + targetSpellLevel;

    // --------------------------------------------------------------------------------------------
    // Время накладывания (Casting Time)
    // --------------------------------------------------------------------------------------------
    public enum CastingTimeType
    {
        Action,
        BonusAction,
        Reaction,
        Minute1,
        Minute10,
        Hour1,
        Special
    }

    public static CastingTimeType GetCastingTime() => CastingTimeType.Action;

    // --------------------------------------------------------------------------------------------
    // Длительность (Duration)
    // --------------------------------------------------------------------------------------------
    public static bool IsInstantaneous() => false;
    public static int DurationRounds() => 10; // пример
    public static bool DurationRequiresConcentration(string spellId) => RequiresConcentration(spellId);

    // --------------------------------------------------------------------------------------------
    // Школы магии
    // --------------------------------------------------------------------------------------------
    public enum MagicSchool
    {
        Abjuration, Conjuration, Divination, Enchantment,
        Evocation, Illusion, Necromancy, Transmutation
    }

    public static MagicSchool GetSchool() => MagicSchool.Evocation; // заглушка

    // --------------------------------------------------------------------------------------------
    // Свитки заклинаний
    // --------------------------------------------------------------------------------------------
    public static bool CanUseSpellScroll(int characterLevel, int spellLevel, bool spellIsOnClassList) =>
        spellIsOnClassList && characterLevel >= (spellLevel * 2 - 1);

    // --------------------------------------------------------------------------------------------
    // Перезарядка классовых умений (Channel Divinity и т.д.)
    // --------------------------------------------------------------------------------------------
    public static bool RechargesOnShortRest() => false;
    public static bool RechargesOnLongRest() => true;
}