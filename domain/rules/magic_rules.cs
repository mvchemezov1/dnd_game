        {
            2 => new() { { 1, 2 } },
            3 => new() { { 1, 3 } },
            4 => new() { { 1, 3 } },
            5 => new() { { 1, 4 }, { 2, 2 } },
            6 => new() { { 1, 4 }, { 2, 2 } },
            7 => new() { { 1, 4 }, { 2, 3 } },
