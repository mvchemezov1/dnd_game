namespace dnd_game.application.security
{
    /// <summary>
    /// Контракт сервиса для получения информации о текущем аутентифицированном пользователе.
    /// Предоставляет доступ к идентификатору пользователя, извлекаемому из контекста безопасности
    /// (например, из claims текущего HTTP-запроса).
    /// </summary>
    /// <remarks>
    /// Реализация должна гарантировать, что метод возвращает идентификатор только в том случае,
    /// если пользователь аутентифицирован; в противном случае допустимо выбросить исключение.
    /// </remarks>
    public interface ICurrentUserService
    {
        /// <summary>
        /// Возвращает идентификатор текущего аутентифицированного пользователя.
        /// </summary>
        /// <returns>GUID идентификатор пользователя.</returns>
        /// <exception cref="System.UnauthorizedAccessException">
        /// Может быть выброшено реализацией, если пользователь не аутентифицирован
        /// или его идентификатор не может быть определён из текущего контекста.
        /// </exception>
        Guid GetCurrentUserId();
    }
}